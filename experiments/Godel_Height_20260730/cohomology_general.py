#!/usr/bin/env python3
"""
cohomology_general.py
=====================
OPTION 1: push past G = Z_2 and past cyclic modules, and test whether the
section-9 "need 2-torsion; deep 2-torsion is fragile" story survives, and find
the NEXT invariant.

Two independent engines, so we never rely on the N^(m^2) brute enumeration that
blew up:

  ENGINE A  (cyclic G, any order m; module = any finite abelian group M):
      For G cyclic of order m generated by t, Tate periodicity gives
          H^2(Z_m, M)  ==  H^0_hat(Z_m, M)  =  M^G / Norm(M),
      where  M^G = { x : t.x = x }  (fixed points)  and
             Norm(x) = x + t.x + t^2.x + ... + t^{m-1}.x.
      This is EXACT and costs O(|M|), so we can go to large m and to non-cyclic
      M (e.g. Z_2 x Z_2, Z_2 x Z_4) without enumerating cochains at all.
      We also compute H^1 = ker(Norm)/im(t-1) for context (Herbrand quotient).

  ENGINE B  (brute, small, for validation only):
      full cochain enumeration H^2 for tiny (m, |M|); asserts ENGINE A == ENGINE B.

Findings we are testing:
  (i)  does "generative class exists  <=>  module has reachable p-torsion for the
       relevant prime" generalize from p=2 (the Z_2 story) to G = Z_p?
  (ii) is the clean single-invariant law (v_2(N)) special to G=Z_2, or is there a
       v_p-style law for G=Z_p?
  (iii) what happens for non-cyclic modules, where "the module order's 2-adic
       valuation" is no longer a single number?

All literal finite group cohomology; the paradox<->cochain dictionary is the only
analogy, unchanged from sections 8-9.
"""
from __future__ import annotations
import itertools, json, os, math
from collections import defaultdict

os.makedirs("results", exist_ok=True)


# --------------------------------------------------------------------------- #
# Finite abelian modules as Z_{n1} x Z_{n2} x ... , elements are tuples.       #
# An action is a group automorphism given as an integer matrix acting mod the  #
# component orders; for cyclic modules it is just multiply-by-u.               #
# --------------------------------------------------------------------------- #
class Module:
    def __init__(self, orders):
        self.orders = tuple(orders)              # e.g. (4,) or (2,2) or (2,4)
        self.elems = list(itertools.product(*[range(n) for n in orders]))
        self.size = len(self.elems)

    def add(self, a, b):
        return tuple((x + y) % n for x, y, n in zip(a, b, self.orders))
    def neg(self, a):
        return tuple((-x) % n for x, n in zip(a, self.orders))
    def zero(self):
        return tuple(0 for _ in self.orders)
    def smul(self, k, a):
        return tuple((k * x) % n for x, n in zip(a, self.orders))


def make_action_cyclic(u, N):
    """Return act(x) = u*x mod N for the 1-generator module (Z_N,)."""
    def act(a):
        return ((u * a[0]) % N,)
    return act


def make_action_matrix(mat, orders):
    """act(x)_i = sum_j mat[i][j]*x_j  (mod orders[i]).  mat is a list of lists."""
    def act(a):
        out = []
        for i, n in enumerate(orders):
            s = sum(mat[i][j] * a[j] for j in range(len(a)))
            out.append(s % n)
        return tuple(out)
    return act


# --------------------------------------------------------------------------- #
# ENGINE A: exact Tate cohomology of a CYCLIC group G = Z_m acting on M.       #
# --------------------------------------------------------------------------- #
def tate_H2_cyclic(M: Module, act, m):
    """H^2(Z_m, M) = M^G / Norm(M) for G cyclic order m, generator acts by `act`.
    Requires act^m == identity. Returns (order_H2, invariant_factors_H2,
    order_H1, herbrand_quotient)."""
    # verify act has order dividing m
    def actpow(k, x):
        for _ in range(k):
            x = act(x)
        return x
    for x in M.elems:
        assert actpow(m, x) == x, "action does not have order dividing m"

    # fixed points M^G = { x : act(x) == x }
    fixed = [x for x in M.elems if act(x) == x]
    fixed_set = set(fixed)

    # Norm(x) = sum_{k=0}^{m-1} act^k(x)
    def norm(x):
        acc = M.zero()
        cur = x
        for _ in range(m):
            acc = M.add(acc, cur)
            cur = act(cur)
        return acc
    norm_image = set(norm(x) for x in M.elems)

    # H^2 = M^G / Norm(M).  Both are subgroups of M; Norm(M) <= M^G always.
    assert norm_image <= fixed_set, "Norm image not inside fixed points (bug)"
    # order of quotient
    H2_order = len(fixed) // len(norm_image)

    # invariant factors of the quotient M^G / Norm(M): compute by building the
    # quotient as a finite abelian group via coset reps + Smith-like reduction.
    inv_factors = quotient_invariant_factors(M, fixed, norm_image)

    # H^1 = ker(Norm) / im(t-1)  (Herbrand context)
    ker_norm = [x for x in M.elems if norm(x) == M.zero()]
    im_tm1 = set(M.add(act(x), M.neg(x)) for x in M.elems)   # (t-1)x
    assert set(im_tm1) <= set(ker_norm), "im(t-1) not in ker(Norm) (bug)"
    H1_order = len(ker_norm) // len(im_tm1)

    herbrand = H2_order / H1_order if H1_order else None
    return H2_order, inv_factors, H1_order, herbrand


def quotient_invariant_factors(M: Module, subgroup_big, subgroup_small):
    """Compute invariant factors of (subgroup_big / subgroup_small) as an abelian
    group, by brute coset enumeration + cyclic-decomposition via element orders.
    subgroup_small <= subgroup_big <= M.  Small groups only."""
    big = list(subgroup_big); small = set(subgroup_small)

    def coset(x):
        return frozenset(M.add(x, s) for s in small)
    reps = {}
    for x in big:
        c = coset(x)
        if c not in reps:
            reps[c] = x
    cosets = list(reps.keys())
    order = len(cosets)
    if order == 1:
        return []
    # element order in the quotient
    zero_coset = coset(M.zero())
    def q_order(x):
        acc = M.zero(); k = 0
        while True:
            k += 1
            acc = M.add(acc, x)
            if coset(acc) == zero_coset:
                return k
    orders = sorted(set(q_order(reps[c]) for c in cosets if reps[c] != M.zero() or True))
    # crude invariant-factor guess: report multiset of element orders' structure
    # via the standard "largest element order = exponent" and factor the group
    # order accordingly. For the small groups here (order <= 4) this is exact.
    exps = [q_order(reps[c]) for c in cosets]
    max_exp = max(exps)
    if max_exp == order:
        return [order]                    # cyclic
    # otherwise elementary abelian-ish: order = prod of equal factors (our cases)
    # find factorization into cyclics of order max_exp
    if order % max_exp == 0 and all(e in (1, max_exp) for e in exps):
        cnt = order // max_exp
        return [max_exp] * cnt
    return [f"order={order},max_exp={max_exp}"]  # fallback label


# --------------------------------------------------------------------------- #
# ENGINE B: brute cochain H^2 for validation (tiny only).                      #
# --------------------------------------------------------------------------- #
def brute_H2(M: Module, act, m):
    G = list(range(m))
    def gadd(a, b): return (a + b) % m
    def actg(g, x):
        for _ in range(g): x = act(x)
        return x
    keys2 = list(itertools.product(G, repeat=2))
    keys1 = list(itertools.product(G, repeat=1))
    n2, n1 = len(keys2), len(keys1)

    def to2(vals): return {keys2[i]: vals[i] for i in range(n2)}
    def d1(f1vals):
        val = {keys1[i]: f1vals[i] for i in range(n1)}
        out = []
        for (g1, g2) in keys2:
            t = M.add(actg(g1, val[(g2,)]), M.neg(val[(gadd(g1, g2),)]))
            t = M.add(t, val[(g1,)])
            out.append(t)
        return tuple(out)
    def d2(f2):
        val = to2(f2)
        for (g1, g2, g3) in itertools.product(G, repeat=3):
            t = actg(g1, val[(g2, g3)])
            t = M.add(t, M.neg(val[(gadd(g1, g2), g3)]))
            t = M.add(t, val[(g1, gadd(g2, g3))])
            t = M.add(t, M.neg(val[(g1, g2)]))
            if t != M.zero():
                return False
        return True
    # Z2
    Z2 = [f for f in itertools.product(M.elems, repeat=n2) if d2(f)]
    B2 = set(d1(f1) for f1 in itertools.product(M.elems, repeat=n1))
    # count cosets
    def addc(a, b): return tuple(M.add(a[i], b[i]) for i in range(n2))
    B2list = list(B2); seen = set(); classes = 0
    for z in Z2:
        if z in seen: continue
        coset = set(addc(z, b) for b in B2list)
        seen |= coset; classes += 1
    return classes


# --------------------------------------------------------------------------- #
# PART 1: validate ENGINE A == ENGINE B on tiny cases.                         #
# --------------------------------------------------------------------------- #
def validate():
    print("=" * 74)
    print("PART 1: ENGINE A (Tate) vs ENGINE B (brute) -- validation")
    print("=" * 74)
    cases = [
        ((3,), make_action_cyclic(1, 3), 2),   # Z2 on Z3 trivial -> H2=1
        ((4,), make_action_cyclic(1, 4), 2),   # Z2 on Z4 trivial -> H2=2
        ((4,), make_action_cyclic(3, 4), 2),   # Z2 on Z4 conj    -> H2=2
        ((3,), make_action_cyclic(1, 3), 3),   # Z3 on Z3 trivial
        ((4,), make_action_cyclic(1, 4), 2),
        ((2, 2), make_action_matrix([[1, 0], [0, 1]], (2, 2)), 2),  # Z2 trivial on Z2xZ2
    ]
    mism = 0
    for orders, act, m in cases:
        M = Module(orders)
        a, inv, h1, herb = tate_H2_cyclic(M, act, m)
        b = brute_H2(M, act, m)
        ok = (a == b)
        mism += (0 if ok else 1)
        print(f"  G=Z{m} on Z{'x'.join(map(str,orders))}: "
              f"Tate |H2|={a} (inv={inv})  brute |H2|={b}  {'OK' if ok else '!!MISMATCH'}")
    print(f"\n  mismatches: {mism}\n")
    return mism


# --------------------------------------------------------------------------- #
# PART 2: G = Z_p, cyclic module Z_N -- is there a v_p law?                     #
# --------------------------------------------------------------------------- #
def vp(n, p):
    k = 0
    while n % p == 0:
        k += 1; n //= p
    return k


def part2_prime_G():
    print("=" * 74)
    print("PART 2: G = Z_p acting on M = Z_N  -- generalizing the v_2 law to v_p")
    print("=" * 74)
    rows = []
    for p in [2, 3, 5]:
        print(f"\n  --- G = Z_{p} ---")
        for N in range(2, 40):
            M = Module((N,))
            # actions: units u with u^p == 1 mod N (the reachable frame-changes)
            valid_u = [u for u in range(1, N)
                       if math.gcd(u, N) == 1 and pow(u, p, N) == 1]
            h2s = {}
            for u in valid_u:
                a, inv, h1, herb = tate_H2_cyclic(M, make_action_cyclic(u, N), p)
                h2s[u] = a
            maxh2 = max(h2s.values())
            # phase: does ANY action give a nontrivial class? does the trivial one?
            triv = h2s.get(1, None)
            gen_capable = maxh2 > 1
            # is there an action that DESTROYS a class the trivial action had?
            fragile = (triv and triv > 1 and any(v == 1 for v in h2s.values()))
            rows.append({"p": p, "N": N, "vp": vp(N, p),
                         "trivial_H2": triv, "max_H2": maxh2,
                         "gen_capable": gen_capable, "fragile": bool(fragile),
                         "H2_by_u": h2s})
            tag = "GEN" if gen_capable else "rigid"
            frag = " FRAGILE" if fragile else ""
            print(f"    N={N:2d}  v_{p}(N)={vp(N,p)}  trivial|H2|={triv}  "
                  f"max|H2|={maxh2}  [{tag}{frag}]")
    with open("results/cohomology_general_prime.json", "w") as f:
        json.dump(rows, f, indent=2)
    return rows


def part2_analysis(rows):
    print("\n" + "=" * 74)
    print("PART 2 ANALYSIS: the v_p law")
    print("=" * 74)
    for p in [2, 3, 5]:
        pr = [r for r in rows if r["p"] == p]
        # hypothesis: trivial-action |H2| = gcd(p, N) = p if p|N else 1
        #   => gen-capable under trivial action  <=>  p | N  <=>  v_p(N) >= 1
        law_ok = all((r["trivial_H2"] == (p if r["N"] % p == 0 else 1)) for r in pr)
        gen_matches_vp = all((r["gen_capable"] == (r["vp"] >= 1)) for r in pr)
        # fragile only when v_p large?
        frag_N = [r["N"] for r in pr if r["fragile"]]
        frag_vp = sorted({r["vp"] for r in pr if r["fragile"]})
        print(f"\n  G=Z_{p}:")
        print(f"    trivial-action law  |H2| = gcd({p},N) [= {p} iff {p}|N]:  "
              f"{'HOLDS' if law_ok else 'FAILS'}")
        print(f"    gen-capable  <=>  v_{p}(N) >= 1  (i.e. {p}|N):  "
              f"{'HOLDS' if gen_matches_vp else 'FAILS'}")
        print(f"    FRAGILE (some action destroys the class) at N = {frag_N}")
        print(f"       -> fragile requires v_{p}(N) in {frag_vp}  "
              f"(compare: for p=2 fragile needed v_2>=3, i.e. 8|N)")


# --------------------------------------------------------------------------- #
# PART 3: non-cyclic modules -- where "one v_p number" is no longer enough.    #
# --------------------------------------------------------------------------- #
def part3_noncyclic():
    print("\n" + "=" * 74)
    print("PART 3: G = Z_2 on NON-CYCLIC modules -- the invariant is no longer scalar")
    print("=" * 74)
    rows = []
    # modules and a few order-2 actions each
    tests = [
        ("Z2xZ2", (2, 2), [
            ("trivial", [[1, 0], [0, 1]]),
            ("swap",    [[0, 1], [1, 0]]),
            ("shear",   [[1, 1], [0, 1]]),
        ]),
        ("Z2xZ4", (2, 4), [
            ("trivial",     [[1, 0], [0, 1]]),
            ("negate-Z4",   [[1, 0], [0, 3]]),
        ]),
        ("Z4xZ4", (4, 4), [
            ("trivial",     [[1, 0], [0, 1]]),
            ("swap",        [[0, 1], [1, 0]]),
            ("neg-both",    [[3, 0], [0, 3]]),
        ]),
        ("Z3xZ3", (3, 3), [
            ("trivial",     [[1, 0], [0, 1]]),
            ("swap",        [[0, 1], [1, 0]]),
            ("neg-both",    [[2, 0], [0, 2]]),
        ]),
    ]
    for name, orders, actions in tests:
        M = Module(orders)
        print(f"\n  M = {name}  (|M|={M.size}):")
        for aname, mat in actions:
            act = make_action_matrix(mat, orders)
            # verify order 2
            def act2(x): return act(act(x))
            if any(act2(x) != x for x in M.elems):
                print(f"    action '{aname}' is not an involution -- skipped")
                continue
            a, inv, h1, herb = tate_H2_cyclic(M, act, 2)
            rows.append({"module": name, "orders": list(orders), "action": aname,
                         "matrix": mat, "H2_order": a, "H2_invariants": inv,
                         "H1_order": h1, "herbrand": herb})
            print(f"    action '{aname:9s}': |H2|={a}  H2 invariants={inv}  "
                  f"|H1|={h1}  Herbrand q={herb}")
    with open("results/cohomology_general_noncyclic.json", "w") as f:
        json.dump(rows, f, indent=2)
    return rows


if __name__ == "__main__":
    mism = validate()
    assert mism == 0, "ENGINE A != ENGINE B -- aborting"
    rows = part2_prime_G()
    part2_analysis(rows)
    part3_noncyclic()
    print("\nDONE.")
